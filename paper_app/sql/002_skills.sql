ALTER TABLE item_grants DROP CONSTRAINT item_grants_kind_check;
ALTER TABLE item_grants ADD CHECK (kind IN ('paper','document','comment','skill'));

CREATE TABLE skills (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id BIGINT NOT NULL REFERENCES accounts(id) DEFERRABLE,
    audience TEXT NOT NULL CHECK (audience IN ('owner', 'users', 'local', 'all', 'ai')),
    title TEXT NOT NULL,
    description TEXT NOT NULL,
    markdown TEXT NOT NULL,
    tags TEXT NOT NULL,
    search_text TEXT NOT NULL,
    archived INTEGER NOT NULL DEFAULT 0 CHECK (archived IN (0,1)),
    revision BIGINT NOT NULL DEFAULT 1,
    created TEXT NOT NULL DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')),
    updated TEXT NOT NULL DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'))
);

CREATE TABLE skill_tags (
    skill_id BIGINT NOT NULL REFERENCES skills(id) ON DELETE CASCADE DEFERRABLE,
    tag TEXT NOT NULL,
    PRIMARY KEY (skill_id,tag)
);

CREATE INDEX skill_tags_search ON skill_tags(tag,skill_id);
