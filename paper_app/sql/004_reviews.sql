CREATE TABLE review_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    requester_id BIGINT NOT NULL REFERENCES accounts(id) DEFERRABLE,
    agent_id BIGINT NOT NULL REFERENCES accounts(id) DEFERRABLE,
    agent_role TEXT NOT NULL CHECK (agent_role IN ('local','cloud')),
    kind TEXT NOT NULL CHECK (kind IN ('paper','document','thread')),
    target_id BIGINT NOT NULL,
    position INTEGER,
    post INTEGER NOT NULL CHECK (post IN (0,1)),
    status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','complete','failed')),
    response TEXT NOT NULL DEFAULT '',
    comment_id BIGINT REFERENCES comments(id) DEFERRABLE
);
CREATE INDEX reviews_requester ON review_requests(requester_id,kind,target_id,id);
CREATE INDEX reviews_agent ON review_requests(agent_id,status,id);
