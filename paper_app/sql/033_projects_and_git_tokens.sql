CREATE TABLE projects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, owner_id BIGINT NOT NULL REFERENCES accounts(id) DEFERRABLE,
    title TEXT NOT NULL, description TEXT NOT NULL, revision BIGINT NOT NULL DEFAULT 1,
    git_revision BIGINT NOT NULL DEFAULT 1, refs TEXT NOT NULL, pack BYTEA NOT NULL,
    created TEXT NOT NULL DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'))
);
CREATE TABLE project_members (
    project_id BIGINT NOT NULL REFERENCES projects(id) DEFERRABLE, account_id BIGINT NOT NULL REFERENCES accounts(id) DEFERRABLE,
    access TEXT NOT NULL CHECK(access IN ('read','write')), PRIMARY KEY(project_id,account_id)
);
CREATE TABLE project_experiments (
    experiment_id BIGINT PRIMARY KEY REFERENCES experiments(id) DEFERRABLE, project_id BIGINT NOT NULL REFERENCES projects(id) DEFERRABLE
);
CREATE TABLE physical_proposals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, owner_id BIGINT NOT NULL REFERENCES accounts(id) DEFERRABLE,
    project_id BIGINT REFERENCES projects(id) DEFERRABLE, title TEXT NOT NULL, plan TEXT NOT NULL,
    revision BIGINT NOT NULL DEFAULT 1
);
CREATE TABLE git_tokens (
    id TEXT PRIMARY KEY, token_hash BYTEA NOT NULL UNIQUE, account_id BIGINT NOT NULL REFERENCES accounts(id) DEFERRABLE,
    kind TEXT NOT NULL, resource_id BIGINT NOT NULL, access TEXT NOT NULL CHECK(access IN ('read','write')),
    expires BIGINT NOT NULL
);
