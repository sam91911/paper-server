CREATE TABLE experiment_compute_tasks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    experiment_id BIGINT NOT NULL REFERENCES experiments(id) DEFERRABLE,
    creator_id BIGINT NOT NULL REFERENCES accounts(id) DEFERRABLE,
    claimant_id BIGINT REFERENCES accounts(id) DEFERRABLE,
    title TEXT NOT NULL,
    instructions TEXT NOT NULL,
    resources TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'open' CHECK (status IN ('open','claimed','complete','cancelled')),
    result TEXT NOT NULL DEFAULT '',
    revision BIGINT NOT NULL DEFAULT 1
);
CREATE INDEX experiment_compute_tasks_experiment ON experiment_compute_tasks(experiment_id,id);
