-- Initial PostgreSQL schema.
CREATE EXTENSION IF NOT EXISTS citext;

-- Keep unique indexes small for paths and CSV fields that may exceed a btree entry.
CREATE FUNCTION paper_text_hash(value text)
RETURNS bytea LANGUAGE sql IMMUTABLE STRICT PARALLEL SAFE
SET search_path = pg_catalog
RETURN sha256(convert_to(value, 'UTF8'));

CREATE TABLE accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username CITEXT NOT NULL UNIQUE,
    password_hash BYTEA NOT NULL,
    salt BYTEA NOT NULL,
    role TEXT NOT NULL DEFAULT 'user' CHECK (role IN ('user', 'ai')),
    ai_location TEXT NOT NULL DEFAULT 'cloud' CHECK (ai_location IN ('local', 'cloud')),
    display_name TEXT NOT NULL DEFAULT '',
    email CITEXT,
    trusted BIGINT NOT NULL DEFAULT 1 CHECK (trusted IN (0,1))
);

CREATE TABLE sessions (
    token_hash BYTEA PRIMARY KEY,
    account_id BIGINT NOT NULL REFERENCES accounts(id) DEFERRABLE,
    expires BIGINT NOT NULL
);

CREATE TABLE human_invites (
    token_hash BYTEA PRIMARY KEY, email CITEXT NOT NULL, expires BIGINT NOT NULL
);

CREATE TABLE application_keys (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, account_id BIGINT NOT NULL REFERENCES accounts(id) DEFERRABLE,
    label TEXT NOT NULL, token_hash BYTEA NOT NULL UNIQUE,
    created TEXT NOT NULL DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'))
);

CREATE TABLE google_flows (
    state_hash BYTEA PRIMARY KEY,
    verifier TEXT NOT NULL,
    nonce TEXT NOT NULL,
    expires BIGINT NOT NULL
);

CREATE TABLE google_identities (
    subject TEXT PRIMARY KEY,
    account_id BIGINT NOT NULL UNIQUE REFERENCES accounts(id) DEFERRABLE
);

CREATE TABLE papers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, path TEXT NOT NULL, sha256 TEXT UNIQUE,
    doi TEXT NOT NULL DEFAULT '', title TEXT NOT NULL DEFAULT '',
    authors TEXT NOT NULL DEFAULT '', year TEXT NOT NULL DEFAULT '',
    venue TEXT NOT NULL DEFAULT '', publisher TEXT NOT NULL DEFAULT '',
    source TEXT NOT NULL DEFAULT ''
);

CREATE TABLE paper_metadata_checks (
    paper_id BIGINT PRIMARY KEY REFERENCES papers(id) DEFERRABLE,
    allow_title BIGINT NOT NULL DEFAULT 0,
    next_check BIGINT NOT NULL DEFAULT 0,
    detected_doi TEXT
);

CREATE TABLE archived_papers (
    paper_id BIGINT PRIMARY KEY REFERENCES papers(id) DEFERRABLE
);

CREATE TABLE paper_paths (
    path TEXT NOT NULL, paper_id BIGINT NOT NULL REFERENCES papers(id) DEFERRABLE
);

CREATE TABLE metrics (
    paper_id BIGINT NOT NULL REFERENCES papers(id) DEFERRABLE, page BIGINT NOT NULL,
    metric TEXT NOT NULL, value TEXT NOT NULL, unit TEXT NOT NULL,
    conditions TEXT NOT NULL, evidence TEXT NOT NULL,
    cursor_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY
);

CREATE TABLE groups (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name CITEXT NOT NULL UNIQUE
);

CREATE TABLE memberships (
    paper_id BIGINT NOT NULL REFERENCES papers(id) DEFERRABLE,
    group_id BIGINT NOT NULL REFERENCES groups(id) DEFERRABLE,
    PRIMARY KEY (paper_id, group_id)
);

CREATE TABLE item_grants (
    kind TEXT NOT NULL CHECK (kind IN ('paper','document','comment')),
    item_id BIGINT NOT NULL,
    account_id BIGINT NOT NULL REFERENCES accounts(id) DEFERRABLE,
    PRIMARY KEY (kind,item_id,account_id)
);

CREATE TABLE paper_access (
    paper_id BIGINT PRIMARY KEY REFERENCES papers(id) DEFERRABLE,
    owner_id BIGINT NOT NULL REFERENCES accounts(id) DEFERRABLE,
    audience TEXT NOT NULL CHECK (audience IN ('owner', 'users', 'local', 'all', 'ai'))
);

CREATE TABLE documents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id BIGINT NOT NULL REFERENCES accounts(id) DEFERRABLE,
    audience TEXT NOT NULL CHECK (audience IN ('owner', 'users', 'local', 'all', 'ai')),
    title TEXT NOT NULL,
    markdown TEXT NOT NULL,
    updated TEXT NOT NULL DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')),
    revision BIGINT NOT NULL DEFAULT 1
);

CREATE TABLE experiments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, owner_id BIGINT NOT NULL REFERENCES accounts(id) DEFERRABLE, title TEXT NOT NULL,
    description TEXT NOT NULL DEFAULT '', paper_id BIGINT REFERENCES papers(id) DEFERRABLE,
    audience TEXT NOT NULL DEFAULT 'owner', revision BIGINT NOT NULL DEFAULT 1,
    created TEXT NOT NULL DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')), updated TEXT NOT NULL DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')),
    research_document_id BIGINT REFERENCES documents(id) DEFERRABLE
);

CREATE TABLE experiment_runs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, experiment_id BIGINT NOT NULL REFERENCES experiments(id) DEFERRABLE,
    owner_id BIGINT NOT NULL REFERENCES accounts(id) DEFERRABLE, title TEXT NOT NULL, description TEXT NOT NULL DEFAULT '',
    status TEXT NOT NULL DEFAULT 'planned', audience TEXT NOT NULL DEFAULT 'owner', revision BIGINT NOT NULL DEFAULT 1,
    created TEXT NOT NULL DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')), updated TEXT NOT NULL DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')),
    methods TEXT NOT NULL DEFAULT '', settings TEXT NOT NULL DEFAULT ''
);

CREATE TABLE research_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, experiment_id BIGINT NOT NULL REFERENCES experiments(id) DEFERRABLE,
    run_id BIGINT REFERENCES experiment_runs(id) DEFERRABLE, owner_id BIGINT NOT NULL REFERENCES accounts(id) DEFERRABLE,
    kind TEXT NOT NULL CHECK(kind IN ('code','environment','equipment','tool_record','data')),
    title TEXT NOT NULL, audience TEXT NOT NULL DEFAULT 'owner', revision BIGINT NOT NULL DEFAULT 1,
    created TEXT NOT NULL DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'))
);

CREATE TABLE research_versions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, item_id BIGINT NOT NULL REFERENCES research_items(id) DEFERRABLE,
    number BIGINT NOT NULL, creator_id BIGINT NOT NULL REFERENCES accounts(id) DEFERRABLE,
    description TEXT NOT NULL DEFAULT '', filename TEXT NOT NULL DEFAULT '',
    external_ref TEXT NOT NULL DEFAULT '', sha256 TEXT, content BYTEA,
    created TEXT NOT NULL DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')), UNIQUE(item_id,number)
);

CREATE TABLE research_grants (
    kind TEXT NOT NULL CHECK(kind IN ('experiment','run','item','tool')),
    item_id BIGINT NOT NULL, account_id BIGINT NOT NULL REFERENCES accounts(id) DEFERRABLE,
    can_edit BIGINT NOT NULL DEFAULT 0 CHECK(can_edit IN (0,1)),
    PRIMARY KEY(kind,item_id,account_id)
);

CREATE TABLE research_tools (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, owner_id BIGINT NOT NULL REFERENCES accounts(id) DEFERRABLE, name TEXT NOT NULL,
    version TEXT NOT NULL DEFAULT '', description TEXT NOT NULL DEFAULT '', instructions TEXT NOT NULL DEFAULT '',
    audience TEXT NOT NULL DEFAULT 'owner', image_digest TEXT NOT NULL, command_json TEXT NOT NULL,
    revision BIGINT NOT NULL DEFAULT 1, created TEXT NOT NULL DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'))
);

CREATE TABLE tool_approvers (account_id BIGINT PRIMARY KEY REFERENCES accounts(id) DEFERRABLE);

CREATE TABLE tool_jobs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, experiment_id BIGINT NOT NULL REFERENCES experiments(id) DEFERRABLE,
    run_id BIGINT NOT NULL REFERENCES experiment_runs(id) DEFERRABLE, tool_id BIGINT NOT NULL REFERENCES research_tools(id) DEFERRABLE,
    requester_id BIGINT NOT NULL REFERENCES accounts(id) DEFERRABLE, approver_id BIGINT REFERENCES accounts(id) DEFERRABLE,
    request_json TEXT NOT NULL, request_hash TEXT NOT NULL, status TEXT NOT NULL DEFAULT 'pending',
    log TEXT NOT NULL DEFAULT '', created TEXT NOT NULL DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')),
    updated TEXT NOT NULL DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'))
);

CREATE TABLE research_findings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, document_id BIGINT NOT NULL REFERENCES documents(id) DEFERRABLE,
    author_id BIGINT NOT NULL REFERENCES accounts(id) DEFERRABLE, author_role TEXT NOT NULL, statement TEXT NOT NULL,
    kind TEXT NOT NULL CHECK (kind IN ('observation','baseline','run_result')),
    metric TEXT NOT NULL, value TEXT NOT NULL, unit TEXT NOT NULL, conditions TEXT NOT NULL,
    evidence TEXT NOT NULL, revision BIGINT NOT NULL DEFAULT 1
);

CREATE TABLE research_goals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, document_id BIGINT NOT NULL REFERENCES documents(id) DEFERRABLE,
    author_id BIGINT NOT NULL REFERENCES accounts(id) DEFERRABLE, author_role TEXT NOT NULL,
    question TEXT NOT NULL, rationale TEXT NOT NULL, uncertainty TEXT NOT NULL,
    priority BIGINT, selected BIGINT NOT NULL DEFAULT 0, deferred BIGINT NOT NULL DEFAULT 0,
    revision BIGINT NOT NULL DEFAULT 1, created TEXT NOT NULL DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'))
    );

CREATE TABLE research_goal_evidence (
    goal_id BIGINT NOT NULL REFERENCES research_goals(id) DEFERRABLE,
    finding_id BIGINT NOT NULL REFERENCES research_findings(id) DEFERRABLE, PRIMARY KEY(goal_id,finding_id)
    );

CREATE TABLE research_goal_briefs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, goal_id BIGINT NOT NULL REFERENCES research_goals(id) DEFERRABLE,
    author_id BIGINT NOT NULL REFERENCES accounts(id) DEFERRABLE, author_role TEXT NOT NULL,
    stage TEXT NOT NULL CHECK(stage IN ('feasibility','design')),
    approach TEXT NOT NULL, baseline_id BIGINT NOT NULL REFERENCES research_findings(id) DEFERRABLE,
    criterion TEXT NOT NULL, conditions TEXT NOT NULL, budget TEXT NOT NULL,
    origin_decision_id BIGINT,
    experiment_id BIGINT UNIQUE REFERENCES experiments(id) DEFERRABLE,
    confirmed_by BIGINT REFERENCES accounts(id) DEFERRABLE, confirmed TEXT, baseline_snapshot TEXT,
    created TEXT NOT NULL DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'))
    );

CREATE TABLE research_goal_decisions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, brief_id BIGINT NOT NULL REFERENCES research_goal_briefs(id) DEFERRABLE,
    run_id BIGINT NOT NULL UNIQUE REFERENCES experiment_runs(id) DEFERRABLE,
    result_id BIGINT NOT NULL REFERENCES research_findings(id) DEFERRABLE,
    author_id BIGINT NOT NULL REFERENCES accounts(id) DEFERRABLE, outcome TEXT NOT NULL, next_step TEXT NOT NULL,
    rationale TEXT NOT NULL, evidence TEXT NOT NULL, created TEXT NOT NULL DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'))
    );

CREATE TABLE research_goal_changes (
    goal_id BIGINT NOT NULL REFERENCES research_goals(id) DEFERRABLE, revision BIGINT NOT NULL,
    actor_id BIGINT NOT NULL REFERENCES accounts(id) DEFERRABLE, action TEXT NOT NULL,
    priority BIGINT, selected BIGINT NOT NULL,
    created TEXT NOT NULL DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')), PRIMARY KEY(goal_id,revision)
    );

CREATE TABLE comment_id_sequence (
    singleton BIGINT PRIMARY KEY CHECK (singleton = 1), last_id BIGINT NOT NULL
);

CREATE TABLE comments (
    id BIGINT PRIMARY KEY,
    paper_id BIGINT REFERENCES papers(id) DEFERRABLE,
    document_id BIGINT REFERENCES documents(id) DEFERRABLE,
    body TEXT NOT NULL,
    updated TEXT NOT NULL DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')),
    parent_id BIGINT REFERENCES comments(id) ON DELETE SET NULL DEFERRABLE,
    audience TEXT CHECK (audience IN ('owner','users','local','all','ai')),
    deleted BIGINT NOT NULL DEFAULT 0,
    doi_refs TEXT NOT NULL DEFAULT '[]',
    target_kind TEXT,
    target_id BIGINT,
    target_position BIGINT, finding_id BIGINT REFERENCES research_findings(id) DEFERRABLE, goal_id BIGINT REFERENCES research_goals(id) DEFERRABLE,
    CHECK ((paper_id IS NULL) != (document_id IS NULL))
);

CREATE TABLE comment_authors (
    comment_id BIGINT PRIMARY KEY REFERENCES comments(id) ON DELETE CASCADE DEFERRABLE,
    account_id BIGINT NOT NULL REFERENCES accounts(id) DEFERRABLE,
    kind TEXT NOT NULL CHECK (kind IN ('user', 'ai'))
);

ALTER TABLE research_goal_briefs ADD FOREIGN KEY (origin_decision_id) REFERENCES research_goal_decisions(id) DEFERRABLE;

CREATE UNIQUE INDEX paper_paths_unique ON paper_paths (paper_text_hash(path));

CREATE INDEX paper_paths_lookup ON paper_paths USING hash(path);

CREATE UNIQUE INDEX metrics_unique ON metrics (
    paper_id,page,paper_text_hash(metric),paper_text_hash(value),paper_text_hash(unit),
    paper_text_hash(conditions),paper_text_hash(evidence)
);

CREATE INDEX research_runs_experiment ON experiment_runs(experiment_id,id);

CREATE INDEX research_items_experiment ON research_items(experiment_id,run_id,id);

CREATE UNIQUE INDEX trusted_account_email ON accounts(email) WHERE trusted=1;

CREATE INDEX findings_document ON research_findings(document_id,id);

CREATE INDEX goals_document ON research_goals(document_id,id);

CREATE INDEX goal_briefs_goal ON research_goal_briefs(goal_id,id);

CREATE INDEX goal_decisions_brief ON research_goal_decisions(brief_id,id);

CREATE INDEX goal_evidence_finding ON research_goal_evidence(finding_id);

CREATE INDEX goal_baseline_finding ON research_goal_briefs(baseline_id);

CREATE INDEX goal_result_finding ON research_goal_decisions(result_id);

CREATE INDEX comments_finding ON comments(finding_id) WHERE finding_id IS NOT NULL;

CREATE INDEX comments_goal ON comments(goal_id) WHERE goal_id IS NOT NULL;

CREATE INDEX experiments_document ON experiments(research_document_id);

CREATE INDEX comments_parent ON comments(parent_id);

CREATE INDEX comments_paper_root ON comments(paper_id, parent_id);

CREATE INDEX comments_document_root ON comments(document_id, parent_id);

CREATE INDEX documents_updated ON documents(updated DESC, id DESC);
