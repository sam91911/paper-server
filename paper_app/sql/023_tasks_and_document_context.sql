CREATE TABLE document_contexts (
    document_id BIGINT PRIMARY KEY REFERENCES documents(id) ON DELETE CASCADE DEFERRABLE,
    topic TEXT NOT NULL DEFAULT '',
    research_goal_id BIGINT REFERENCES research_goals(id) DEFERRABLE,
    agent_goal_id BIGINT REFERENCES agent_goals(id) DEFERRABLE,
    CHECK (research_goal_id IS NULL OR agent_goal_id IS NULL)
);

CREATE TABLE tasks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id BIGINT NOT NULL REFERENCES accounts(id) DEFERRABLE,
    assignee_id BIGINT REFERENCES accounts(id) DEFERRABLE,
    title TEXT NOT NULL,
    description TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'open' CHECK (status IN ('open','in_progress','closed')),
    due_on TEXT,
    issue_url TEXT,
    revision BIGINT NOT NULL DEFAULT 1
);
CREATE INDEX tasks_owner ON tasks(owner_id);
CREATE INDEX tasks_assignee ON tasks(assignee_id);
