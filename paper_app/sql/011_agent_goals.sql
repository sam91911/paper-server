CREATE TABLE agent_goals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    requester_id BIGINT NOT NULL REFERENCES accounts(id) DEFERRABLE,
    agent_id BIGINT NOT NULL REFERENCES accounts(id) DEFERRABLE,
    agent_role TEXT NOT NULL CHECK (agent_role IN ('local','cloud')),
    objective TEXT NOT NULL,
    acceptance_criteria TEXT NOT NULL,
    sources TEXT NOT NULL,
    status TEXT NOT NULL CHECK (status IN ('assigned','in_progress','blocked','paused','submitted','completed','canceled')),
    revision BIGINT NOT NULL,
    created BIGINT NOT NULL,
    updated BIGINT NOT NULL
);

CREATE TABLE agent_goal_events (
    goal_id BIGINT NOT NULL REFERENCES agent_goals(id) DEFERRABLE,
    revision BIGINT NOT NULL,
    actor_id BIGINT NOT NULL REFERENCES accounts(id) DEFERRABLE,
    request_id TEXT NOT NULL,
    request_hash TEXT NOT NULL,
    action TEXT NOT NULL,
    status TEXT NOT NULL,
    note TEXT NOT NULL,
    evidence TEXT NOT NULL,
    created BIGINT NOT NULL,
    PRIMARY KEY (goal_id,revision),
    UNIQUE (actor_id,request_id)
);

CREATE INDEX agent_goals_requester ON agent_goals(requester_id,id);
CREATE INDEX agent_goals_agent ON agent_goals(agent_id,id);
